"use client";
import { useState } from "react";
import { fetchWithTimeout } from "@/lib/http";

interface Props {
  repoUrl: string;
  claims: any[];
  evidence: Record<string, any>;
  verdicts: any[];
}

function buildMarkdownReport(
  repoUrl: string,
  claims: any[],
  evidence: Record<string, any>,
  verdicts: any[]
): string {
  const timestamp = new Date().toISOString();
  let trueCount = 0;
  let driftCount = 0;
  let unverifiedCount = 0;

  const rows = claims.map((c, idx) => {
    const id = c.id || `claim-${idx + 1}`;
    const vf = verdicts.find((v) => v.claimId === id);
    const verdict = vf?.verdict || "UNVERIFIED";
    if (verdict === "TRUE") trueCount++;
    else if (verdict === "SPEC-DRIFT") driftCount++;
    else unverifiedCount++;

    const ev = evidence[id] || {};
    const files = Array.isArray(ev.files) && ev.files.length ? ev.files.slice(0, 3).join(", ") : "None";
    const ref = vf?.specReference ? `\`${vf.specReference.replace(/\|/g, "\\|")}\`` : vf?.reason || "";
    return `| ${idx + 1} | **${verdict}** | ${String(c.text || "").replace(/\|/g, "\\|")} | \`${files}\` | ${ref} |`;
  });

  const score = claims.length ? Math.round((trueCount / claims.length) * 100) : 0;

  return [
    `# VibeCheck Build-Honesty Audit Report`,
    ``,
    `- **Repository:** ${repoUrl || "N/A"}`,
    `- **Generated At:** ${timestamp}`,
    `- **Build Honesty Score:** **${score}%** (${trueCount} TRUE · ${driftCount} SPEC-DRIFT · ${unverifiedCount} UNVERIFIED)`,
    ``,
    `## Claim-by-Claim Verdicts`,
    ``,
    `| # | Verdict | Claim | Matched Files | Server-Verified Citation / Reason |`,
    `| --- | --- | --- | --- | --- |`,
    ...rows,
    ``,
    `> Generated by **VibeCheck** — static/API-based repository & spec-drift verifier.`,
  ].join("\n");
}

export function ReportExport({ repoUrl, claims, evidence, verdicts }: Props) {
  const [permalink, setPermalink] = useState("");
  const [copiedMd, setCopiedMd] = useState(false);
  const [error, setError] = useState("");
  const [busy, setBusy] = useState(false);
  const hasClaims = claims.length > 0;

  async function handleGenerate() {
    setBusy(true);
    setError("");
    try {
      const res = await fetchWithTimeout("/api/generate-report", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ repoUrl, claims, evidence, verdicts }),
      });
      const data = await res.json();
      if (!res.ok || data.error) {
        throw new Error(data.error || `generate-report failed (${res.status})`);
      }
      setPermalink(data.permalink);
    } catch (err) {
      setError(err instanceof Error ? err.message : String(err));
    } finally {
      setBusy(false);
    }
  }

  function handleExportJson() {
    const payload = { repoUrl, claims, evidence, verdicts, generatedAt: new Date().toISOString() };
    const blob = new Blob([JSON.stringify(payload, null, 2)], { type: "application/json" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = "vibecheck-report.json";
    a.click();
    URL.revokeObjectURL(url);
  }

  function handleExportMarkdown() {
    const md = buildMarkdownReport(repoUrl, claims, evidence, verdicts);
    const blob = new Blob([md], { type: "text/markdown;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = "vibecheck-audit-report.md";
    a.click();
    URL.revokeObjectURL(url);
  }

  async function handleCopyMarkdown() {
    try {
      const md = buildMarkdownReport(repoUrl, claims, evidence, verdicts);
      await navigator.clipboard.writeText(md);
      setCopiedMd(true);
      setTimeout(() => setCopiedMd(false), 2500);
    } catch {
      handleExportMarkdown();
    }
  }

  return (
    <div className="space-y-3">
      <div className="flex flex-wrap gap-2">
        <button
          onClick={handleGenerate}
          disabled={busy || !hasClaims}
          className="inline-flex items-center gap-2 rounded-lg bg-emerald-600 px-4 py-2.5 text-sm font-semibold text-white transition-colors hover:bg-emerald-500 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-emerald-500/50 disabled:cursor-not-allowed disabled:opacity-60"
        >
          {busy ? "Generating..." : "Generate Shareable Report"}
        </button>
        <button
          onClick={handleCopyMarkdown}
          disabled={!hasClaims}
          className="rounded-lg border border-zinc-300 bg-white px-3.5 py-2.5 text-sm font-medium text-zinc-700 transition-colors hover:bg-zinc-50 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-zinc-400 disabled:cursor-not-allowed disabled:opacity-60 dark:border-zinc-700 dark:bg-zinc-800 dark:text-zinc-300 dark:hover:bg-zinc-700"
        >
          {copiedMd ? "✓ Copied PR Markdown Table" : "Copy PR Audit Markdown"}
        </button>
        <button
          onClick={handleExportMarkdown}
          disabled={!hasClaims}
          className="rounded-lg border border-zinc-300 bg-white px-3.5 py-2.5 text-sm font-medium text-zinc-700 transition-colors hover:bg-zinc-50 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-zinc-400 disabled:cursor-not-allowed disabled:opacity-60 dark:border-zinc-700 dark:bg-zinc-800 dark:text-zinc-300 dark:hover:bg-zinc-700"
        >
          Export Report (.md)
        </button>
        <button
          onClick={handleExportJson}
          disabled={!hasClaims}
          className="rounded-lg border border-zinc-300 bg-white px-3.5 py-2.5 text-sm font-medium text-zinc-700 transition-colors hover:bg-zinc-50 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-zinc-400 disabled:cursor-not-allowed disabled:opacity-60 dark:border-zinc-700 dark:bg-zinc-800 dark:text-zinc-300 dark:hover:bg-zinc-700"
        >
          Export Report (JSON)
        </button>
      </div>
      {!hasClaims ? (
        <p className="text-xs text-zinc-500 dark:text-zinc-400">
          Run a check or load demo data first &mdash; a report needs claims.
        </p>
      ) : null}
      {error ? (
        <p className="text-sm font-medium text-red-600 dark:text-red-400">{error}</p>
      ) : null}
      {permalink ? (
        <div className="space-y-1.5 rounded-lg border border-emerald-200 bg-emerald-50/60 p-3 dark:border-emerald-500/30 dark:bg-emerald-950/20">
          <div className="flex flex-wrap items-center justify-between gap-2">
            <a
              href={permalink}
              target="_blank"
              rel="noreferrer"
              className="text-sm font-semibold text-emerald-700 underline underline-offset-2 hover:text-emerald-600 dark:text-emerald-400 dark:hover:text-emerald-300"
            >
              Open shareable report in new tab &rarr;
            </a>
            <span className="font-mono text-[11px] text-zinc-500 dark:text-zinc-400">
              Self-contained Base64URL permalink
            </span>
          </div>
          <p className="break-all font-mono text-[11px] leading-relaxed text-zinc-500 dark:text-zinc-400">
            {permalink}
          </p>
        </div>
      ) : null}
    </div>
  );
}
